const assert = require('node:assert/strict');
const {spawn,spawnSync} = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require('playwright');
const {pythonPath, browserOptions, stopServer} = require('./browser-support.cjs');

const root = path.resolve(__dirname,'..');
const scratch = fs.mkdtempSync(path.join(root,'.notebook-test-'));
const output = path.join(root,'artifacts','ui');
const python = pythonPath(root);
const port = 17869;
const base = `http://127.0.0.1:${port}`;
const env = {...process.env,LIT_PORT:String(port),LIT_DB_PATH:path.join(scratch,'test.db'),
  LIT_DATA_DIR:path.join(scratch,'data'),DEEPSEEK_API_KEY:'',LIT_API_KEY:''};

async function main() {
  const fixture = spawnSync(python,['-X','utf8','-m','tests.notebook_fixture'],{
    cwd:root,env,encoding:'utf8',windowsHide:true,
  });
  if (fixture.status !== 0) throw new Error(fixture.stderr || fixture.stdout);
  const seeded = JSON.parse(fixture.stdout);
  const server = spawn(python,['-m','lit_agent.webui'],{cwd:root,env,windowsHide:true,stdio:'ignore'});
  let browser;
  try {
    for (let i=0;i<100;i++) {
      if (server.exitCode !== null) throw new Error('Notebook test server exited');
      try { if ((await fetch(base+'/api/health')).ok) break; } catch {}
      await new Promise(resolve=>setTimeout(resolve,200));
    }
    browser = await chromium.launch(browserOptions());
    const page = await browser.newPage({viewport:{width:1600,height:1000}});
    const errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto(base,{waitUntil:'networkidle'});
    await page.getByText('我的笔记',{exact:true}).click();
    await page.locator('#notebook-count').filter({hasText:'2 篇笔记'}).waitFor();
    await page.locator(`.notebook-item[data-task-id="${seeded.notes[0]}"]`).click();
    const pdf = page.locator('#notebook-pdf');
    await pdf.locator('canvas').waitFor();
    await page.locator('#notebook-body .citation-button').first().click();
    await page.waitForFunction(()=>document.querySelector('#notebook-pdf').dataset.page==='2');
    assert.match(await page.locator('#notebook-evidence-text').textContent(),/graph encoder/);
    const ink = await pdf.locator('canvas').evaluate(canvas=>{
      const pixels=canvas.getContext('2d').getImageData(0,0,canvas.width,canvas.height).data;
      let n=0; for(let i=0;i<pixels.length;i+=4) if(pixels[i]<160&&pixels[i+3]>0)n++;
      return n;
    });
    assert(ink>500,'Notebook PDF is blank');
    await page.screenshot({path:path.join(output,'notebook-desktop.png')});
    await page.getByRole('button',{name:'收藏笔记',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#notebook-star').getAttribute('aria-pressed')==='true');
    await page.getByLabel('笔记范围',{exact:true}).selectOption('starred');
    await page.locator('#notebook-count').filter({hasText:'1 篇笔记'}).waitFor();
    await page.getByRole('button',{name:'编辑笔记',exact:true}).click();
    const editor=page.locator('#notebook-editor');
    await editor.fill((await editor.inputValue())+'\n\n人工补充的实现分析。');
    await page.locator('#notebook-save').click();
    await page.locator('#notebook-body').filter({hasText:'人工补充的实现分析'}).waitFor();
    assert.equal(await page.locator('#notebook-versions option').count(),2);
    await page.getByLabel('笔记历史版本').selectOption('1');
    assert(!(await page.locator('#notebook-body').textContent()).includes('人工补充'));
    await page.getByLabel('笔记历史版本').selectOption('2');
    const bundle=await page.request.get(new URL(await page.locator('#notebook-bundle').getAttribute('href'),base).href);
    assert.equal(bundle.headers()['content-type'],'application/zip');
    assert.equal((await bundle.body()).subarray(0,2).toString(),'PK');
    await page.getByRole('button',{name:'移入回收站',exact:true}).click();
    await page.getByLabel('笔记范围',{exact:true}).selectOption('trash');
    await page.locator('#notebook-count').filter({hasText:'1 篇笔记'}).waitFor();
    await page.getByRole('button',{name:'恢复笔记',exact:true}).click();
    await page.locator('#notebook-count').filter({hasText:'0 篇笔记'}).waitFor();
    await page.getByLabel('笔记范围',{exact:true}).selectOption('all');
    await page.locator(`.notebook-item[data-task-id="${seeded.notes[1]}"]`).click();
    await page.waitForFunction(()=>document.querySelector('#notebook-source').options.length===2);
    assert.equal(await page.locator('#notebook-source option').count(),2);
    await page.getByLabel('笔记对应论文').selectOption(String(seeded.documents[1]));
    await page.waitForFunction(id=>document.querySelector('#notebook-pdf').dataset.documentId===String(id),seeded.documents[1]);
    await page.reload({waitUntil:'networkidle'});
    await page.locator('#notebook-title').waitFor({state:'visible'});
    assert.equal(await page.locator('#notebook-title').inputValue(),'两篇论文方法对比');

    await page.locator('label[for=tab5]').click();
    await page.getByLabel('选择阅读论文').selectOption(String(seeded.papers[0]));
    const savedProfile=await (await page.request.get(base+'/api/profile')).json();
    await page.locator('label[for=tab6]').click();
    const templateUrl='**/api/note-templates/paper-reading';
    let releaseDetail, detailStarted;
    let detailGate=new Promise(resolve=>{releaseDetail=resolve});
    let detailRequest=new Promise(resolve=>{detailStarted=resolve});
    const holdDetail=async route=>{detailStarted();await detailGate;await route.continue()};
    await page.route(templateUrl,holdDetail);
    await page.getByRole('button',{name:'个人模板',exact:true}).click();
    const dialog=page.locator('#templates-dialog');
    await detailRequest;
    assert.match(await page.locator('#template-body').inputValue(),/概括论文解决的问题/);
    assert.match(await page.locator('#template-preview').textContent(),/研究问题与动机/);
    assert.equal(await page.locator('#template-editor').getAttribute('aria-busy'),'true');
    assert(await page.locator('#template-use').isDisabled(),'Pending templates must not be submitted');
    releaseDetail();
    await page.locator('#template-editor[aria-busy=false]').waitFor();
    await page.unroute(templateUrl,holdDetail);
    assert.equal(await dialog.locator('.template-choice').count(),2);
    assert.equal(await page.locator('#template-history').isVisible(),false,'A single version needs no dropdown');
    const catalog=await (await page.request.get(base+`/api/note-template-fields?paper_ids=${seeded.papers[0]}`)).json();
    assert.equal(await page.locator('#template-variable optgroup').count(),3);
    assert.equal(await page.locator('#template-variable option').count(),21);
    await dialog.locator('[data-template-id=paper-reproduction]').click();
    await page.locator('#template-editor[aria-busy=false]').waitFor();
    assert.match(await page.locator('#template-body').inputValue(),/原文未报告/);

    await page.route(templateUrl,route=>route.fulfill({status:503,json:{detail:'Temporary failure'}}));
    await dialog.locator('[data-template-id=paper-reading]').click();
    await page.locator('#template-retry').waitFor({state:'visible'});
    assert.match(await page.locator('#template-body').inputValue(),/概括论文解决的问题/);
    assert(await page.locator('#template-copy').isDisabled(),'Failed loads must not save stale data');
    await page.unroute(templateUrl);
    await page.locator('#template-retry').click();
    await page.locator('#template-editor[aria-busy=false]').waitFor();
    assert.equal(await page.locator('#template-retry').isVisible(),false);

    detailGate=new Promise(resolve=>{releaseDetail=resolve});
    detailRequest=new Promise(resolve=>{detailStarted=resolve});
    await page.route(templateUrl,holdDetail);
    await dialog.locator('[data-template-id=paper-reading]').click();
    await detailRequest;
    await dialog.getByRole('button',{name:'新建模板',exact:true}).click();
    assert.equal(await page.locator('#template-body').inputValue(),'');
    assert.equal(await page.locator('#template-preview').textContent(),'');
    assert.equal(await page.locator('#template-name').inputValue(),'');
    assert.equal(await page.locator('#template-description').inputValue(),'');
    assert.equal(await page.locator('#template-versions option').count(),0);
    assert.equal(await page.locator('#template-history').isVisible(),false,'Unsaved drafts have no version history');
    assert.equal(await page.locator('#template-state').textContent(),'草稿 · 未保存');
    await page.screenshot({path:path.join(output,'note-template-new-blank.png')});
    await page.locator('#template-name').fill('我的研究模板');
    const oldResponse=page.waitForResponse(response=>response.url().endsWith('/api/note-templates/paper-reading'));
    releaseDetail();
    await oldResponse;
    await page.unroute(templateUrl,holdDetail);
    assert.equal(await page.locator('#template-name').inputValue(),'我的研究模板','A late response overwrote the draft');
    assert.equal(await page.locator('#template-body').inputValue(),'','A late response restored the old body');
    assert.equal(await page.locator('#template-state').textContent(),'未保存');
    await page.locator('#template-description').fill('适用于图学习论文');
    const templateBody=page.locator('#template-body'), fieldMenu=page.getByLabel('插入动态字段',{exact:true});
    for (const field of catalog.fields) {
      await templateBody.fill('');
      await fieldMenu.focus();
      await fieldMenu.selectOption(field.id);
      assert.equal(await templateBody.inputValue(),`{{${field.id}}}`);
      assert.equal(await page.locator('#template-insert-status').textContent(),`已插入：${field.label}`);
      assert((await page.locator('#template-preview').textContent()).includes(catalog.values[field.id]),
        `Field ${field.id} did not resolve in the preview`);
    }
    await templateBody.fill('# \n\n## 阅读目标\n待替换\n\n保留这段内容。');
    await templateBody.evaluate(input=>{
      const start=input.value.indexOf('待替换');
      input.setSelectionRange(start,start+'待替换'.length);
    });
    await fieldMenu.focus();
    await fieldMenu.selectOption('reading_purpose');
    assert.equal(await templateBody.inputValue(),'# \n\n## 阅读目标\n{{reading_purpose}}\n\n保留这段内容。');
    assert.equal(await templateBody.evaluate(input=>input.value.slice(input.selectionStart,input.selectionEnd)),'{{reading_purpose}}');
    assert.equal(await page.locator('#template-insert-status').textContent(),'已插入：阅读目的');
    assert((await page.locator('#template-preview').textContent()).includes(savedProfile.purpose));
    await templateBody.evaluate(input=>input.setSelectionRange(2,2));
    await fieldMenu.focus();
    await fieldMenu.selectOption('paper_title');
    assert.equal(await templateBody.inputValue(),'# {{paper_title}}\n\n## 阅读目标\n{{reading_purpose}}\n\n保留这段内容。');
    assert.equal(await page.locator('#template-preview h1').textContent(),'Graph Learning Study');
    assert.equal(await fieldMenu.inputValue(),'');
    await page.screenshot({path:path.join(output,'template-fields-desktop.png')});
    await templateBody.fill('一段需要保留的长正文。\n'.repeat(100));
    await templateBody.evaluate(input=>{input.setSelectionRange(input.value.length,input.value.length);input.scrollTop=0});
    await fieldMenu.focus();
    await fieldMenu.selectOption('paper_title');
    await page.waitForFunction(()=>document.querySelector('#template-body').scrollTop>0);
    assert.equal(await templateBody.evaluate(input=>input.value.slice(input.selectionStart,input.selectionEnd)),'{{paper_title}}');
    await templateBody.fill('x'.repeat(12000));
    await fieldMenu.selectOption('reading_purpose');
    assert.equal((await templateBody.inputValue()).length,12000,'Field insertion bypassed the length limit');
    assert(!((await templateBody.inputValue()).includes('{{')));
    page.once('dialog',event=>event.accept());
    await dialog.getByRole('button',{name:'新建模板',exact:true}).click();
    assert.equal(await templateBody.inputValue(),'');
    assert.equal(await page.locator('#template-preview').textContent(),'');
    assert.equal(await page.locator('#template-insert-status').textContent(),'');
    assert.equal(await fieldMenu.inputValue(),'');
    assert.equal(await templateBody.evaluate(input=>input.selectionStart+input.selectionEnd+input.scrollTop),0);
    await page.locator('#template-name').fill('我的研究模板');
    await page.locator('#template-description').fill('适用于图学习论文');
    await page.locator('#template-body').fill('# {{paper_title}}\n\n## 方法直觉\n解释核心机制。\n\n## 原文证据\n保留引用。\n\n<script>window.injected=true</script>');
    assert.equal(await page.locator('#template-preview script').count(),0);
    assert.equal(await page.evaluate(()=>window.injected),undefined);
    await page.getByRole('button',{name:'保存模板',exact:true}).click();
    await page.locator('#template-state').filter({hasText:'当前 v1'}).waitFor();
    assert.equal(await page.locator('#template-history').isVisible(),false);
    await page.screenshot({path:path.join(output,'note-template-desktop.png')});
    const personalId=await page.locator('.template-choice.selected').getAttribute('data-template-id');
    await page.locator('#template-body').fill('# {{paper_title}}\n\n## 方法直觉\n解释核心机制。\n\n## 原文证据\n保留引用。\n\n## 下一步\n列出验证计划。');
    let releaseSave, saveStarted;
    const saveGate=new Promise(resolve=>{releaseSave=resolve});
    const saveRequest=new Promise(resolve=>{saveStarted=resolve});
    const holdSave=async route=>{
      if (route.request().method()==='PUT') {saveStarted();await saveGate}
      await route.continue();
    };
    const personalUrl=`**/api/note-templates/${personalId}`;
    await page.route(personalUrl,holdSave);
    await page.getByRole('button',{name:'保存模板',exact:true}).click();
    await saveRequest;
    page.once('dialog',event=>event.accept());
    await dialog.getByRole('button',{name:'新建模板',exact:true}).click();
    assert.equal(await templateBody.inputValue(),'');
    assert.equal(await page.locator('#template-preview').textContent(),'');
    await page.locator('#template-name').fill('新的独立草稿');
    await templateBody.fill('# 不可被旧请求覆盖');
    releaseSave();
    await page.locator('#toast').filter({hasText:'模板已保存 · v2'}).waitFor();
    await page.unroute(personalUrl,holdSave);
    assert.equal(await templateBody.inputValue(),'# 不可被旧请求覆盖');
    assert.equal(await page.locator('#template-name').inputValue(),'新的独立草稿');
    assert.equal(await page.locator('#template-versions option').count(),0);
    page.once('dialog',event=>event.accept());
    await dialog.locator(`[data-template-id="${personalId}"]`).click();
    await page.locator('#template-state').filter({hasText:'当前 v2'}).waitFor();
    assert.equal(await page.locator('#template-versions option').count(),2);
    assert.equal(await page.locator('#template-history').isVisible(),true);
    const latestBody=await templateBody.inputValue();
    await page.getByLabel('模板历史版本',{exact:true}).selectOption('1');
    assert(!(await templateBody.inputValue()).includes('## 下一步'));
    await templateBody.fill((await templateBody.inputValue())+'\n历史版本的未保存修改');
    page.once('dialog',event=>event.dismiss());
    await page.getByLabel('模板历史版本',{exact:true}).selectOption('2');
    assert.equal(await page.locator('#template-versions').inputValue(),'1','Cancelling a switch must retain the displayed version');
    assert((await templateBody.inputValue()).includes('历史版本的未保存修改'));
    page.once('dialog',event=>event.accept());
    await page.getByLabel('模板历史版本',{exact:true}).selectOption('2');
    assert.equal(await templateBody.inputValue(),latestBody);
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(output,'note-template-mobile.png')});
    assert(await dialog.evaluate(node=>node.scrollWidth<=node.clientWidth+2),'Template dialog overflows');
    await page.getByRole('button',{name:'用于本次阅读',exact:true}).click();
    const chosen=await page.locator('#reading-template').inputValue();
    assert(chosen && chosen!=='paper-reading' && chosen!=='paper-reproduction');
    assert.equal(await page.locator('#reading-template').getAttribute('data-version'),'2');
    let submitted;
    await page.route('**/api/chat/runs',route=>{
      submitted=route.request().postDataJSON();
      return route.fulfill({json:{id:seeded.notes[0]}});
    });
    await page.getByLabel('选择阅读论文').selectOption(String(seeded.papers[0]));
    await page.getByRole('button',{name:'开始阅读',exact:true}).click();
    assert.equal(submitted.template_id,chosen);
    assert.equal(submitted.template_version,2);
    await page.getByText('我的笔记',{exact:true}).click();
    await page.locator(`.notebook-item[data-task-id="${seeded.notes[0]}"]`).click();
    await page.locator(`#notebook-detail[data-task-id="${seeded.notes[0]}"][aria-busy="false"]`).waitFor();
    await page.locator('#notebook-body .citation-button').first().click();
    await pdf.locator('canvas').waitFor();
    await page.waitForFunction(()=>document.querySelector('#notebook-pdf').dataset.page==='2');
    await page.screenshot({path:path.join(output,'notebook-mobile.png')});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),'Notebook overflows mobile');
    await page.setViewportSize({width:1366,height:768});
    await page.getByText('我的文献库',{exact:true}).click();
    await page.locator('.note-count-button').first().click();
    await page.locator('#notebook-count').filter({hasText:'2 篇笔记'}).waitFor();
    await page.locator('#notebook-clear-paper').waitFor({state:'visible'});
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({notes:'passed',templates:'passed',citations:'passed',exports:'passed',ink,errors,output}));
  } catch (error) {
    console.error('Notebook browser failure:',error);
    throw error;
  } finally {
    await browser?.close();
    await stopServer(server);
    const target=fs.realpathSync(scratch), workspace=fs.realpathSync(root);
    if (path.dirname(target).toLowerCase()!==workspace.toLowerCase() || !path.basename(target).startsWith('.notebook-test-'))
      throw new Error('Refusing cleanup outside the notebook test workspace');
    fs.rmSync(target,{recursive:true,force:true,maxRetries:8,retryDelay:250});
  }
}
main().catch(error=>{console.error(error);process.exitCode=1});
